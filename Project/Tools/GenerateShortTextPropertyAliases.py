"""Validate reviewed alias JSON against source registrations and generate the pure lookup header."""
from pathlib import Path
import argparse
import json
import re

PROJECT=Path(__file__).resolve().parents[1]
CATALOG=PROJECT/'EditorTools/ShortTextPropertyAliases.json'
HEADER=PROJECT/'KashipanEngine/Utilities/ShortTextPropertyAliasCatalog.generated.h'

def key(text):
    text=text.translate(str.maketrans('ＸＹＺｘｙｚ．－＋（），','xyzxyz.-+(),'))
    text=text.translate({ord(chr(0xFF10+i)):str(i) for i in range(10)})
    return re.sub(r'[\s　。、！!]','',text).lower()

def registrations():
    result={}
    for path in (PROJECT/'KashipanEngine').rglob('*.h'):
        source=path.read_text(encoding='utf-8-sig')
        for scope,macro in [('object','REGISTER_COMPONENT_OBJECT'),('scene','REGISTER_COMPONENT_SCENE')]:
            for name in re.findall(r'^'+macro+r'\((\w+)\)',source,re.M):
                result[name]=(scope,path.relative_to(PROJECT/'KashipanEngine').as_posix())
    return result

def generate(document):
    actual=registrations();seen=set();component_words={};members=0
    lines=['// Generated by Tools/GenerateShortTextPropertyAliases.py; edit the JSON catalogue instead.',
        '#pragma once','#include <string>','#include <vector>','namespace KashipanEngine::ShortText {',
        'struct PropertyMemberAliases { std::string member; std::vector<std::string> aliases; };',
        'struct PropertyComponentAliases { std::string component; bool scene; std::vector<std::string> aliases; std::vector<PropertyMemberAliases> members; };',
        'inline const std::vector<PropertyComponentAliases> &PropertyAliasCatalog() {',
        '    static const std::vector<PropertyComponentAliases> entries = {']
    literal=lambda s:json.dumps(s,ensure_ascii=False)
    strings=lambda values:'{'+', '.join(literal(s) for s in values)+'}'
    for entry in sorted(document['components'],key=lambda x:x['component']):
        name=entry['component']
        if name in seen or name not in actual:raise ValueError('Unknown or duplicate component: '+name)
        seen.add(name);scope=entry.get('scope','object')
        if actual[name][0]!=scope:raise ValueError('Wrong scope: '+name)
        words=[name]+entry['aliases']
        if len(entry['aliases'])<2:raise ValueError('At least two component aliases required: '+name)
        for word in words:
            normalized=key(word)
            if not normalized or len(word.encode('utf8'))>128:raise ValueError('Invalid alias: '+word)
            old=component_words.setdefault((scope,normalized),name)
            if old!=name:raise ValueError(f'Ambiguous component alias {word}: {old}/{name}')
        member_names=set();member_words={};rows=[]
        for item in entry['members']:
            member=item['member']
            if member in member_names:raise ValueError('Duplicate member: '+name+'.'+member)
            member_names.add(member);members+=1
            if len(item['aliases'])<2:raise ValueError('At least two member aliases required: '+name+'.'+member)
            evidence=PROJECT/'KashipanEngine'/item['evidence']
            evidence_name=re.sub(r'\[\d+\]', '', member)
            if not evidence.is_file() or evidence_name not in evidence.read_text(encoding='utf-8-sig'):
                raise ValueError('Missing member evidence: '+name+'.'+member)
            aliases=list(dict.fromkeys([member,member.rstrip('_')]+item['aliases']))
            for word in aliases:
                normalized=key(word)
                old=member_words.setdefault(normalized,member)
                if old!=member:raise ValueError(f'Ambiguous member alias {name}:{word}: {old}/{member}')
            rows.append('{'+literal(member)+', '+strings(aliases)+'}')
        lines.append('        {'+literal(name)+', '+('true' if scope=='scene' else 'false')+', '+strings(list(dict.fromkeys(words)))+', {'+', '.join(rows)+'}},')
    missing=set(actual)-seen
    if missing:raise ValueError('Missing registered components: '+', '.join(sorted(missing)))
    lines+=['    };','    return entries;','}','} // namespace KashipanEngine::ShortText','']
    generated='\n'.join(lines)
    if not HEADER.exists() or HEADER.read_text(encoding='utf8')!=generated:
        HEADER.write_text(generated,encoding='utf8')
    print(f'{len(seen)} components / {members} members; alias collisions checked; {HEADER}')

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--merge',nargs='+',type=Path)
    args=parser.parse_args()
    if args.merge:
        entries=[item for path in args.merge for item in json.loads(path.read_text(encoding='utf-8-sig'))['components']]
        document={'version':1,'components':sorted(entries,key=lambda x:x['component'])}
        generate(document)
        CATALOG.write_text(json.dumps(document,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    else:generate(json.loads(CATALOG.read_text(encoding='utf-8-sig')))
if __name__=='__main__':main()
